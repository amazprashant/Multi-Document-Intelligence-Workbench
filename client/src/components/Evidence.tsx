import { useState } from "react";
import type { Evidence } from "@workbench/shared";

/** Source chip: document name + location; click to reveal the verbatim quote. */
export function SourceChip({ e }: { e: Evidence }) {
  const [open, setOpen] = useState(false);
  return (
    <span className="chip-wrap">
      <button type="button" className={`chip ${e.verified ? "" : "chip-warn"}`} onClick={() => setOpen(!open)} aria-expanded={open}
        title={e.verified ? "Quote found in source text" : "Quote NOT found in source text"}>
        📄 {e.documentName}{e.location ? ` · ${e.location}` : ""}{e.verified ? "" : " ⚠"}
      </button>
      {open && <blockquote className="quote">“{e.quote}”{!e.verified && <em> — could not be verified against the source</em>}</blockquote>}
    </span>
  );
}

export const FactBadge = () => <span className="badge badge-fact" title="Value copied from the document with a verbatim quote">Extracted fact</span>;
export const AiBadge = () => <span className="badge badge-ai" title="Judgement generated by the AI from extracted facts">AI interpretation</span>;
